  await page.goto(target); await ready();
  assert.ok(await page.locator('[data-parcel]').count());
  assert.equal(await page.locator('[data-building]').count(), 0);
  assert.deepEqual(await page.locator('#plotOp option').evaluateAll(nodes => nodes.map(n => n.value)), ['cutPlots', 'cutCourtyards', 'garden', 'cutPlots + raffinement']);
  assert.ok(!(await page.locator('#buildingOp option').evaluateAll(nodes => nodes.map(n => n.value))).includes('detached'));
  const baseline = await geometry('[data-parcel]');
  await page.locator('#plotsParams [data-param="frontage.1"]').fill('14');
  await page.locator('#plotsParams [data-param="frontage.1"]').dispatchEvent('change');
  await page.locator('#plotsParams [data-param="frontage.0"]').fill('9');
